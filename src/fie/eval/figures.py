"""Figure-level retrieval labels, generated from the store and the chunks.

ADR 0011's labels are `SectionRef` — any chunk in the right section counts —
so the retrieval eval cannot see whether the chunk *carrying a figure* was
delivered, which is exactly the failure behind `expected_fact_coverage`
(ADR 0020). The gold set for "query → the chunk carrying this figure" needs
no hand labelling and no model: for a fact in `ingest.db`, the chunks whose
text prints its filing-scale mantissa *are* the answer. Free, offline, and
regenerated by `uv run eval-seed` whenever the corpus changes.
"""

import json
import logging
from pathlib import Path

from fie.eval.datasets import FigureQuery, GoldQuestion
from fie.ingest.store import Fact, IngestStore

logger = logging.getLogger(__name__)

# The analyst-facing headline concepts, with the words an analyst would use.
# Deliberately narrow: this measures figure *delivery* for the question class
# the system exists to answer, not every tagged number in a filing.
HEADLINE_CONCEPTS = {
    "us-gaap:RevenueFromContractWithCustomerExcludingAssessedTax": "total revenue",
    "us-gaap:Revenues": "total revenue",
    "us-gaap:NetIncomeLoss": "net income",
    "us-gaap:ResearchAndDevelopmentExpense": "research and development expense",
    "us-gaap:GrossProfit": "gross profit",
    "us-gaap:OperatingIncomeLoss": "operating income",
    "us-gaap:OperatingExpenses": "total operating expenses",
    "us-gaap:Assets": "total assets",
    "us-gaap:Liabilities": "total liabilities",
    "us-gaap:StockholdersEquity": "total stockholders' equity",
    "us-gaap:CashAndCashEquivalentsAtCarryingValue": "cash and cash equivalents",
    "us-gaap:SellingGeneralAndAdministrativeExpense": (
        "selling, general and administrative expense"
    ),
}

COMPANY_NAMES = {"TSLA": "Tesla", "AAPL": "Apple", "NVDA": "Nvidia"}

# Scales a filing prints amounts at: units, thousands, millions.
_SCALES = (1e6, 1e3, 1.0)

# Smallest mantissa usable as a target, i.e. four significant digits. The
# 3-digit billions form false-positives badly — "161" for 161,148,000,000
# matches arbitrary filing text, and it produced two spurious "the figure was
# available" readings during the 2026-07-30 diagnosis before the rule was
# tightened.
_MIN_MANTISSA = 1000


def mantissas(value: float) -> list[str]:
    """Every filing-scale rendering of `value` carrying at least four
    significant digits, comma and bare form."""
    out: list[str] = []
    for scale in _SCALES:
        quotient = abs(value) / scale
        rounded = round(quotient)
        if abs(quotient - rounded) > 1e-6 or rounded < _MIN_MANTISSA:
            continue
        out.extend((f"{rounded:,}", str(rounded)))
    return out


def load_chunks(chunks_dir: Path) -> dict[str, list[tuple[str, str]]]:
    """Every ingested chunk's text, grouped by ticker."""
    by_ticker: dict[str, list[tuple[str, str]]] = {}
    for path in sorted(chunks_dir.glob("*.json")):
        for chunk in json.loads(path.read_text())["chunks"]:
            by_ticker.setdefault(chunk["ticker"], []).append((chunk["chunk_id"], chunk["text"]))
    return by_ticker


def _gold_wording(gold: list[GoldQuestion]) -> list[tuple[str, list[str], int, str]]:
    """The production query string for figures the gold set already asks
    about: (ticker, concept terms, fiscal year, question).

    A single-part question passes through the decomposer verbatim, so the
    gold question *is* what `research` retrieves with — which is what makes
    the 2026-07-30 findings' production ranks reproducible from this set.
    Terms match the concept as substrings, the same way `query_facts` does,
    so a label spelling `RevenueFromContractWithCustomer` still claims
    `us-gaap:RevenueFromContractWithCustomerExcludingAssessedTax`."""
    return [
        (
            expected.ticker.upper(),
            [term.lower() for term in expected.concept_terms],
            expected.fiscal_year,
            question.question,
        )
        for question in gold
        for expected in question.expected_facts
        if expected.kind == "xbrl" and expected.fiscal_year is not None
    ]


def _lookup(
    wording: list[tuple[str, list[str], int, str]], ticker: str, concept: str, year: int
) -> str | None:
    lowered = concept.lower()
    return next(
        (
            question
            for gold_ticker, terms, gold_year, question in wording
            if gold_ticker == ticker
            and gold_year == year
            and any(term in lowered or lowered in term for term in terms)
        ),
        None,
    )


def _annual(facts: list[Fact], concept: str) -> list[Fact]:
    """The full-year figures of one concept: a duration covering the fiscal
    year, or the balance that closes it — never one of the three quarter-ends
    the same fiscal year also holds."""
    exact = [f for f in facts if f.concept == concept and f.fiscal_year is not None]
    year_end: dict[tuple[str, int], str] = {}
    for fact in exact:
        if fact.period_start is None and fact.period_end:
            key = (fact.ticker, fact.fiscal_year or 0)
            year_end[key] = max(year_end.get(key, ""), fact.period_end)
    return [
        fact
        for fact in exact
        if (fact.period_start is not None and fact.fiscal_period == "FY")
        or (
            fact.period_start is None
            and year_end.get((fact.ticker, fact.fiscal_year or 0)) == fact.period_end
        )
    ]


def build_figure_queries(
    store: IngestStore, chunks_dir: Path, gold: list[GoldQuestion]
) -> list[FigureQuery]:
    """One labeled query per headline annual figure in the corpus."""
    by_ticker = load_chunks(chunks_dir)
    wording = _gold_wording(gold)
    queries: dict[str, FigureQuery] = {}
    unreachable = 0
    for concept, phrase in HEADLINE_CONCEPTS.items():
        facts = store.query_facts(
            concept_terms=[concept], unit="usd", include_dimensioned=False, limit=10**6
        )
        for fact in _annual(facts, concept):
            targets = sorted(
                {
                    chunk_id
                    for chunk_id, text in by_ticker.get(fact.ticker, [])
                    if any(m in text for m in mantissas(fact.value))
                }
            )
            if not targets:
                unreachable += 1
                continue
            company = COMPANY_NAMES.get(fact.ticker, fact.ticker)
            gold_query = _lookup(wording, fact.ticker, concept, fact.fiscal_year or 0)
            # The same figure is filed in every filing that carries it as a
            # comparative; one row per (ticker, concept, year).
            query_id = f"fq-{fact.ticker}-{concept.split(':')[-1]}-{fact.fiscal_year}"
            queries[query_id] = FigureQuery(
                id=query_id,
                query=gold_query
                or f"What was {company}'s {phrase} in fiscal year {fact.fiscal_year}?",
                source="gold" if gold_query else "template",
                ticker=fact.ticker,
                value=fact.value,
                description=f"{fact.ticker} FY{fact.fiscal_year} {phrase}",
                relevant_chunk_ids=targets,
            )
    logger.info("figure labels: %d queries; %d figures no chunk prints", len(queries), unreachable)
    return [queries[key] for key in sorted(queries)]
